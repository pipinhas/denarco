CREATE TABLE demanda (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocolo            VARCHAR(20) UNIQUE,
    categoria_id         BIGINT        NOT NULL REFERENCES categoria (id),
    setor_id             BIGINT REFERENCES setor (id),
    autor_id             BIGINT        NOT NULL REFERENCES usuario (id),
    responsavel_id       BIGINT REFERENCES usuario (id),
    descricao            VARCHAR(1000) NOT NULL,
    status               VARCHAR(20)   NOT NULL,
    urgencia             VARCHAR(10)   NOT NULL,
    alcance              VARCHAR(10)   NOT NULL,
    risco_seguranca      BOOLEAN       NOT NULL DEFAULT FALSE,
    canal                VARCHAR(20)   NOT NULL,
    -- Preenchidos quando um atendente registra em nome de alguém (telefone, presencial).
    solicitante_nome     VARCHAR(120),
    solicitante_telefone VARCHAR(20),
    latitude             DOUBLE PRECISION,
    longitude            DOUBLE PRECISION,
    endereco             VARCHAR(200),
    bairro               VARCHAR(100),
    ponto_referencia     VARCHAR(200),
    foto                 VARCHAR(100),
    pontuacao            INT           NOT NULL DEFAULT 0,
    pontuacao_fixada     BOOLEAN       NOT NULL DEFAULT FALSE,
    -- Contador guardado na demanda para ordenar por apoios sem contar a tabela toda.
    total_apoios         INT           NOT NULL DEFAULT 0,
    ultimo_apoio_em      TIMESTAMP,
    prazo                DATE,
    criada_em            TIMESTAMP     NOT NULL,
    atualizada_em        TIMESTAMP     NOT NULL,
    concluida_em         TIMESTAMP
);
