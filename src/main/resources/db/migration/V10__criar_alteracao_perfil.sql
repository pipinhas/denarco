-- Auditoria de acesso: toda aprovação, promoção ou rebaixamento fica registrada.
CREATE TABLE alteracao_perfil (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       BIGINT      NOT NULL REFERENCES usuario (id),
    perfil_anterior  VARCHAR(20) NOT NULL,
    perfil_novo      VARCHAR(20) NOT NULL,
    setor_id         BIGINT REFERENCES setor (id),
    alterado_por_id  BIGINT      NOT NULL REFERENCES usuario (id),
    criado_em        TIMESTAMP   NOT NULL
);
